import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import {
  extractRepoName,
  formatEvidenceCitation,
  generateHtmlReport,
} from '../src/lib/export.ts'
import type { AnalysisReport } from '../src/lib/types.ts'

describe('Repository Name & Citation Formatting', () => {
  it('extracts repo name correctly from standard GitHub URLs', () => {
    assert.equal(extractRepoName('https://github.com/google-research/bert'), 'google-research/bert')
    assert.equal(extractRepoName('https://github.com/google-research/bert/'), 'google-research/bert')
    assert.equal(extractRepoName('https://github.com/google-research/bert.git'), 'google-research/bert')
    assert.equal(extractRepoName('http://github.com/huggingface/transformers'), 'huggingface/transformers')
    assert.equal(extractRepoName(''), '')
  })

  it('formats evidence citation with range, single line, or file path only', () => {
    // Range
    assert.equal(
      formatEvidenceCitation('modeling.py', 142, 160),
      'modeling.py:L142-L160',
    )
    // Same start and end line
    assert.equal(
      formatEvidenceCitation('modeling.py', 142, 142),
      'modeling.py:L142',
    )
    // Only start line
    assert.equal(
      formatEvidenceCitation('run_classifier.py', 55, null),
      'run_classifier.py:L55',
    )
    // No line numbers
    assert.equal(
      formatEvidenceCitation('extract_features.py', null, null),
      'extract_features.py',
    )
    // Empty path
    assert.equal(
      formatEvidenceCitation('', 10, 20),
      '',
    )
  })
})

describe('HTML Report Generation', () => {
  const sampleReport: AnalysisReport = {
    id: 'test-job-999',
    paper_title: 'BERT: Pre-training of Deep Bidirectional Transformers',
    repo_url: 'https://github.com/google-research/bert',
    created_at: '2026-11-01T00:00:00.000Z',
    model_used: 'gemma4:e4b',
    default_branch: 'master',
    repo_files_indexed: 17,
    repo_python_files: 13,
    results: [
      {
        claim: { id: 'c1', text: 'Trained on 16 TPU chips', page: 3 },
        status: 'supported',
        file_path: 'run_pretraining.py',
        line_start: 100,
        line_end: 115,
        code_snippet: 'flags.DEFINE_integer("num_tpu_cores", 8, "Total number of TPU cores.")',
        explanation: 'Specifies TPU flags and setup.',
        limitations: 'Exact 16 chip cluster topology depends on TPU pod slice configuration.',
      },
      {
        claim: { id: 'c2', text: 'Uses Adam optimizer with warmup', page: 4 },
        status: 'ambiguous',
        file_path: 'optimization.py',
        line_start: 35,
        line_end: 45,
        code_snippet: 'class AdamWeightDecayOptimizer:',
        explanation: 'Custom Adam optimizer implemented.',
        limitations: 'Warmup schedule implemented in separate function.',
      },
      {
        claim: { id: 'c3', text: 'Benchmarked on proprietary TPU v4 infrastructure', page: 7 },
        status: 'missing',
        file_path: null,
        line_start: null,
        line_end: null,
        code_snippet: null,
        explanation: 'No proprietary hardware references found.',
        limitations: 'Hardware setup was internal to Google.',
      },
    ],
    summary: {
      total_claims: 3,
      supported: 1,
      ambiguous: 1,
      missing: 1,
    },
  }

  it('generates a valid, complete standalone HTML report with metadata, distribution and citations', () => {
    const html = generateHtmlReport(sampleReport)

    assert.ok(html.includes('<!DOCTYPE html>'))
    assert.ok(html.includes('PaperTrail Analysis Report'))
    assert.ok(html.includes('BERT: Pre-training of Deep Bidirectional Transformers'))
    assert.ok(html.includes('google-research/bert'))
    assert.ok(html.includes('master'))
    assert.ok(html.includes('17 (13 Python)'))
    assert.ok(html.includes('3 claims analysed'))
    assert.ok(html.includes('Claim Distribution'))
    assert.ok(html.includes('Supported: <strong>1</strong>'))
    assert.ok(html.includes('Ambiguous: <strong>1</strong>'))
    assert.ok(html.includes('Missing: <strong>1</strong>'))
    assert.ok(html.includes('run_pretraining.py:L100-L115'))
    assert.ok(html.includes('flags.DEFINE_integer(&quot;num_tpu_cores&quot;, 8, &quot;Total number of TPU cores.&quot;)'))
    assert.ok(html.includes('Trained on 16 TPU chips'))
    assert.ok(html.includes('Generated by PaperTrail · Local Gemma 4'))
  })

  it('escapes special characters to prevent XSS in HTML report', () => {
    const dangerousReport: AnalysisReport = {
      ...sampleReport,
      paper_title: '<script>alert("xss")</script>',
      results: [
        {
          claim: { id: 'c-xss', text: '<img src=x onerror=alert(1)>' },
          status: 'supported',
          file_path: 'test.py',
          line_start: 1,
          line_end: 2,
          code_snippet: '<tag>&"\'',
          explanation: '<b style="color:red">bold</b>',
          limitations: 'None & all',
        },
      ],
    }

    const html = generateHtmlReport(dangerousReport)
    assert.ok(!html.includes('<script>alert("xss")</script>'))
    assert.ok(html.includes('&lt;script&gt;alert(&quot;xss&quot;)&lt;/script&gt;'))
    assert.ok(!html.includes('<img src=x onerror=alert(1)>'))
    assert.ok(html.includes('&lt;img src=x onerror=alert(1)&gt;'))
  })
})
